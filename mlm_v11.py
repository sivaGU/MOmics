def _safe_read_csv(*args, **kwargs):
    if "encoding" in kwargs:
        return _original_read_csv(*args, **kwargs)
    attempts = [
        dict(encoding="utf-8"),
        dict(encoding="latin-1"),
        dict(encoding="utf-8",  on_bad_lines="skip"),
        dict(encoding="latin-1", on_bad_lines="skip"),
        dict(encoding="latin-1", on_bad_lines="skip", engine="python"),
    ]
    last_err = None
    for extra in attempts:
        try:
            kw = {**extra, **kwargs}  # kwargs override
            return _original_read_csv(*args, **kw)
        except (UnicodeDecodeError, UnicodeError, pd.errors.ParserError) as e:
            last_err = e
            continue
    raise last_err
