def detect_samples(df, exclude=None):
    exclude = (exclude or set()) | META_COLS
    return [c for c in df.columns if c not in exclude]


def _filter_to_features(df, feat_col, target, sample_cols):
    sub = df[df[feat_col].isin(target)].copy()
    if sub.empty:
        return pd.DataFrame(index=target, columns=sample_cols, dtype=float)
    sub["_mean"] = sub[sample_cols].astype(float).mean(axis=1, skipna=True)
    sub = sub.sort_values("_mean", ascending=False).drop_duplicates(feat_col)
    matrix = pd.DataFrame(index=target, columns=sample_cols, dtype=float)
    for f in target:
        hit = sub[sub[feat_col] == f]
        if not hit.empty:
            matrix.loc[f] = hit.iloc[0][sample_cols].astype(float).values
    return matrix


