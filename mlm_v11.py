def _load_by_ensg(file_path, target_symbols, sym2ensg):
    if not file_path.exists(): return None
    df = pd.read_csv(file_path, sep="\t", low_memory=False)
    feat_col = df.columns[0]
    sample_cols = detect_samples(df, exclude={feat_col})
    df["_ensg"] = df[feat_col].astype(str).str.split(".").str[0]
    target_ensgs = {sym2ensg[s]: s for s in target_symbols if s in sym2ensg}
    sub = df[df["_ensg"].isin(target_ensgs.keys())].copy()
    if sub.empty:
        return pd.DataFrame(index=target_symbols, columns=sample_cols, dtype=float)
    sub["_sym"] = sub["_ensg"].map(target_ensgs)
    sub["_mean"] = sub[sample_cols].astype(float).mean(axis=1, skipna=True)
    sub = sub.sort_values("_mean", ascending=False).drop_duplicates("_sym")
    matrix = pd.DataFrame(index=target_symbols, columns=sample_cols, dtype=float)
    for _, r in sub.iterrows():
        matrix.loc[r["_sym"]] = r[sample_cols].astype(float).values
    return matrix


def _load_by_symbol(file_path, target_symbols, feat_col, sep="\t"):
    if not file_path.exists(): return None
