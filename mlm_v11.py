# z-score

def fit_zscore(matrix):
    """matrix: (features × samples). Returns (mean Series, std Series) per feature."""
    means = matrix.mean(axis=1, skipna=True)
    stds  = matrix.std(axis=1, skipna=True).replace(0, 1.0)
    return means, stds


def apply_zscore(matrix, means, stds):
    """Z-score per feature, preserving NaN. Aligns to means.index."""
    out = matrix.copy()
    for f in out.index:
        if f in means.index and not pd.isna(means.loc[f]):
            out.loc[f] = (out.loc[f] - means.loc[f]) / stds.loc[f]
        else:
            out.loc[f] = np.nan
    return out


