def maybe_log1p(matrix):
    """Auto-detect raw counts (max > 50) and apply log1p; else leave alone."""
    vals = matrix.values
    finite = vals[np.isfinite(vals)]
    if len(finite) > 0 and float(np.nanmax(finite)) > 50.0:
        return np.log1p(matrix), True
    return matrix, False


# class balance

def synthetic_balance(X, y, target_per_class=SYNTH_TARGET, noise_sd=SYNTH_NOISE_SD, rng=None):
    """Pad both classes to target_per_class by sampling existing samples + Gaussian noise.
    Operates on z-scored data, so noise_sd is on z-score units."""
    rng = rng or np.random.default_rng(SEED_BASE)
    X_arr = X.values
    y_arr = np.asarray(y)
    pieces_X, pieces_y = [X_arr], [y_arr]
    for cls in (0, 1):
        cls_mask = y_arr == cls
        n_cls = int(cls_mask.sum())
        if n_cls == 0:
            continue
        n_need = target_per_class - n_cls
        if n_need <= 0:
            continue
        cls_data = X_arr[cls_mask]
        idx = rng.integers(0, n_cls, size=n_need)
        synth = cls_data[idx] + rng.normal(0, noise_sd, size=(n_need, cls_data.shape[1]))
        pieces_X.append(synth)
        pieces_y.append(np.full(n_need, cls, dtype=int))
    X_out = pd.DataFrame(np.vstack(pieces_X), columns=X.columns)
    y_out = np.concatenate(pieces_y)
    return X_out, y_out


# CV

def cv_layer(X, y, name, balance=BALANCE_METHOD):
    if len(np.unique(y)) < 2:
        print(f"  {name}: single class"); return np.zeros(len(y)), float("nan")
    n_minor = min((y == 0).sum(), (y == 1).sum())
    n_folds = min(N_FOLDS, n_minor)
    if n_folds < 2:
        print(f"  {name}: only {n_minor} in minor class"); return np.zeros(len(y)), float("nan")

    spw = (y == 0).sum() / max((y == 1).sum(), 1) if balance == "scale_pos_weight" else 1.0

    oof = np.zeros((N_SEEDS, len(y)))
    fold_aucs, train_aucs = [], []
    for s_idx in range(N_SEEDS):
        seed = SEED_BASE + s_idx
        skf = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=seed)
        for tr, te in skf.split(X, y):
            X_tr, y_tr = X.iloc[tr], y[tr]
            if balance == "synthetic":
                X_tr, y_tr = synthetic_balance(X_tr, y_tr,
                                               rng=np.random.default_rng(seed * 1000 + s_idx))
            m = XGBClassifier(**make_sub_params(spw), random_state=seed)
            m.fit(X_tr, y_tr)
            oof[s_idx, te] = m.predict_proba(X.iloc[te])[:, 1]
            if len(np.unique(y[te])) > 1:
                fold_aucs.append(roc_auc_score(y[te], oof[s_idx, te]))
            train_aucs.append(roc_auc_score(y_tr, m.predict_proba(X_tr)[:, 1]))

    oof_mean = oof.mean(axis=0)
    auc = roc_auc_score(y, oof_mean)
    fa, ta = np.array(fold_aucs), np.array(train_aucs)
    print(f"  {name:5s}  OOF AUC={auc:.3f}  per-fold={fa.mean():.3f}±{fa.std():.3f}  "
          f"train={ta.mean():.3f}  gap={ta.mean()-fa.mean():+.3f}  "
          f"[n={len(y)}, {(y==1).sum()}+/{(y==0).sum()}-, balance={balance}]")
    return oof_mean, auc


def fuse(oof_dict, ids_dict, y_dict):
    all_ids = sorted(set().union(*(set(v) for v in ids_dict.values())))
    F = pd.DataFrame(index=all_ids, columns=["P_rna", "P_prot", "P_met"], dtype=float)
    Y = pd.Series(index=all_ids, dtype=float)
    for layer in ["rna", "prot", "met"]:
        for sid, p, lab in zip(ids_dict[layer], oof_dict[layer], y_dict[layer]):
            F.loc[sid, f"P_{layer}"] = p
            Y.loc[sid] = lab
    Y = Y.dropna().astype(int)
    F = F.loc[Y.index]

    skf = StratifiedKFold(N_FOLDS, shuffle=True, random_state=SEED_BASE)
    foof = np.zeros(len(Y))
    for tr, te in skf.split(F, Y):
        m = XGBClassifier(**FUSION_PARAMS, random_state=SEED_BASE)
        m.fit(F.iloc[tr], Y.iloc[tr])
        foof[te] = m.predict_proba(F.iloc[te])[:, 1]
    auc = roc_auc_score(Y, foof)
    pr  = average_precision_score(Y, foof)
    fpr, tpr, thr = roc_curve(Y, foof)
    youden = float(thr[np.argmax(tpr - fpr)])
    sens = float(((foof >= youden) & (Y == 1)).sum() / max((Y == 1).sum(), 1))
    spec = float(((foof <  youden) & (Y == 0)).sum() / max((Y == 0).sum(), 1))

    full = XGBClassifier(**FUSION_PARAMS, random_state=SEED_BASE)
    full.fit(F, Y)
    print(f"\n=== Fusion ===  AUROC={auc:.3f}  PR={pr:.3f}  Youden={youden:.3f}  Sens={sens*100:.1f}%  Spec={spec*100:.1f}%")
    return {"F": F, "Y": Y, "oof": foof, "auc": auc, "pr": pr,
            "youden": youden, "sens": sens, "spec": spec, "model": full}


# feature pruning

def prune_features(X, y, layer_name, balance=BALANCE_METHOD, keep_frac=KEEP_FRAC, min_keep=KEEP_MIN):
    spw = (y == 0).sum() / max((y == 1).sum(), 1) if balance == "scale_pos_weight" else 1.0
    X_tr, y_tr = X, y
    if balance == "synthetic":
        X_tr, y_tr = synthetic_balance(X, y)
    m = XGBClassifier(**make_sub_params(spw), random_state=SEED_BASE)
    m.fit(X_tr, y_tr)
    imp = pd.Series(m.feature_importances_, index=X.columns).sort_values(ascending=False)
    n_keep = max(min_keep, int(np.ceil(len(imp) * keep_frac)))
    surviving = imp.head(n_keep).index.tolist()
    print(f"  {layer_name:5s}  importances: {imp.round(3).to_dict()}")
    print(f"         keep {n_keep}/{len(imp)}: {surviving}")
    print(f"         drop: {imp.tail(len(imp) - n_keep).index.tolist()}")
    return surviving


# external scoring

def score_external(layer_matrices_zscored, sub_models, fusion_model, threshold):
    layer_probs = {}
    sample_set = None
    for layer, df in layer_matrices_zscored.items():
        if df is None or df.empty:
            continue
        X = df.T  # samples × features
        X = X.dropna(how="all")
        if X.empty:
            continue
        # XGBoost will handle remaining NaNs internally
        probs = sub_models[layer].predict_proba(X.values)[:, 1]
        layer_probs[layer] = pd.Series(probs, index=X.index)
        sample_set = set(X.index) if sample_set is None else sample_set | set(X.index)

    if sample_set is None: return None
    sids = sorted(sample_set)
    F = pd.DataFrame(index=sids, columns=["P_rna", "P_prot", "P_met"], dtype=float)
    for layer, ps in layer_probs.items():
        F.loc[ps.index, f"P_{layer}"] = ps.values
    fused = fusion_model.predict_proba(F.values)[:, 1]
    return pd.DataFrame({"sample": sids,
                         "P_rna": F["P_rna"].values, "P_prot": F["P_prot"].values, "P_met": F["P_met"].values,
                         "P_fused": fused, "call_GBM": (fused >= threshold).astype(int)})


