def build_symbol_to_ensg():
    df = pd.read_csv(DISCOVERY_DIR / "rnaseq_washu_readcount.v4.0.tsv", sep="\t", low_memory=False)
    sample_cols = [c for c in df.columns if c.startswith("C3L") or c.startswith("C3N")]
